export type Stage = "ابتدائي" | "متوسط";

export interface BreakCorner {
  id: string;
  /** رقم اليوم داخل الأسبوع كما هو مرقّم في المصدر. */
  day: number;
  /** اسم الركن، مثل «ركن عزنا بأصالتنا». */
  title: string;
  /** نواتج التعلم */
  outcomes: string[];
  /** القيم المستهدفة */
  values: string[];
  /** مدة التنفيذ بالدقائق */
  minutes: number;
  /** مكان التنفيذ */
  place: string;
  /** أدوات التنفيذ */
  tools: string[];
  /** إجراءات التنفيذ خطوة بخطوة */
  steps: string[];
  /** أسئلة جاهزة بإجاباتها، إن وُجدت في المصدر. */
  quiz?: { question: string; answer: string }[];
  /** رابط مرفق يشير إليه رمز استجابة في الصفحة. */
  attachment?: string;
  /** التجربة التفاعلية التي تُشغَّل لهذا الركن. */
  play?: "gallery" | "quiz" | "tree";
}

export interface BreakWeek {
  id: string;
  /** رقم الأسبوع في الفصل الدراسي. */
  week: number;
  stage: Stage;
  /** ملاحظة المرحلة كما في الغلاف، مثل «الصفوف العليا». */
  stageNote: string | null;
  /** المناسبة التي يدور حولها الأسبوع. */
  occasion: string | null;
  /** الشعار المصاحب، إن وُجد. */
  slogan: string | null;
  /** الروتين اليومي الذي يعوّد المعلم الطلاب عليه طوال الأسبوع. */
  dailyRoutine: string[];
  corners: BreakCorner[];
  source: { fileName: string };
}

