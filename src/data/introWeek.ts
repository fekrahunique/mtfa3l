/**
 * الأسبوع التمهيدي الحافل — نموذج «الشاشة الحيّة + سيناريو الرائد».
 * المنصة شاشة تُعرض على البروجكتر أمام الطلاب، ورائد النشاط يقودها بالنقر،
 * وبجانب كل شاشة سيناريو دقيق لما يقوله ويفعله — بلا ورق ولا تحضير.
 *
 * فُرزت أقوى التفاعلات لكل يوم فقط (لا كل ما في الدليل)، واختير ما يصنع
 * أعلى حماس وتحدٍّ وأثر يبقى، ويُبنى تراكميًا حتى يوم الحصاد.
 */

export type ScreenKind =
  | "countdown" // عدّاد الانطلاق (ابتدائي)
  | "cipher" // الرسالة المشفّرة (متوسط)
  | "wheel" // عجلة التعارف / عجلة الحظ
  | "cards" // بطاقات تتقدّم (مواهب/ماذا لو/هوية/بوصلة/صياد الأصوات)
  | "timer" // مؤقّت تحدٍّ عملاق + تحكيم وصدارة
  | "escape" // غرفة الهروب بشفرات
  | "tree" // شجرة الفصل التراكمية
  | "crown" // التتويج وإعلان الرتب / لوحة الصدارة
  | "growth" // محرّك النمو — مشاركة ودعوة
  | "map" // خريطة الكنز — مرافق المدرسة بنقاط ساخنة
  | "wordcloud" // سحابة المواهب — كلمات هوية الفصل
  | "vote" // مناظرة الأبطال — تصويت ورسوم بيانية
  | "tower" // برج المعرفة — كل إجابة صحيحة لبنة، أول من يكمل يفوز
  | "buzzer" // مبارزة الأزرار — جرس رقمي، الأسرع يجيب
  | "cheer" // مقياس الحماس — صوت التشجيع عبر الميكروفون يحرّك المركبة
  | "rhythm" // صدى الإيقاع — تسلسل حركات يكبر كل جولة والفصل يعيده (ذاكرة + حماس)
  | "memory" // بطاقات الذاكرة — طابِق القيمة بسلوكها من الذاكرة
  | "bingo"; // بينغو التعارف — «من ينطبق عليه…» أول خطّ مكتمل يفوز

export interface IntroScreen {
  id: string;
  kind: ScreenKind;
  title: string;
  /** سطر يظهر كبيرًا على شاشة الطلاب */
  headline?: string;
  /** سيناريو الرائد: ماذا يقول ويفعل */
  scenario: string;
  minutes?: number;
  /** بيانات خاصة بنوع الشاشة */
  data?: {
    seconds?: number; // للمؤقّت/العدّاد
    prompts?: string[]; // للبطاقات
    boxes?: { label: string; emoji: string; challenge: string; riddle?: string; piece?: string }[]; // صناديق المواهب / نقاط خريطة الكنز
    treasure?: string; // الكلمة السرّية التي تتجمّع من قطع الخريطة
    reveal?: string; // جملة كشف الكنز النهائية
    criteria?: string[]; // معايير التحكيم
    codes?: { clue: string; answer: string; hint: string; kind: string }[]; // شفرات الهروب
    cipher?: { encoded: string; solved: string; key: string }; // الرسالة المشفّرة
    titles?: { emoji: string; label: string }[]; // ألقاب التتويج
    questions?: string[]; // بنك أسئلة العجلة
    moves?: { emoji: string; label: string }[]; // حركات صدى الإيقاع
    pairs?: { term: string; match: string }[]; // أزواج بطاقات الذاكرة
    cells?: string[]; // خانات بينغو التعارف (٩ عبارات)
  };
}

export interface IntroDay {
  id: string;
  index: number;
  planet: string; // اسم اليوم/الكوكب/المهمة
  emoji: string;
  vibe: string; // الأثر الذي يبقى
  screens: IntroScreen[];
}

export interface IntroTrack {
  stage: "ابتدائي" | "متوسط";
  theme: string;
  tagline: string;
  days: IntroDay[];
}

