export const SCHOOL_START = "2026-08-30";

/** الأيام المتبقية حتى بداية الدراسة (لا تقلّ عن صفر). */
export function daysUntilStart(): number {
  const start = new Date(SCHOOL_START + "T00:00:00").getTime();
  const now = Date.now();
  return Math.max(0, Math.ceil((start - now) / 86400000));
}

